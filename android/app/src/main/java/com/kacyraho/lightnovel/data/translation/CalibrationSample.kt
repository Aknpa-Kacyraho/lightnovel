    fun paragraphs(targetChars: Int): List<String> {
        val out = mutableListOf<String>()
        var size = 0
        var index = 0
        while (size < targetChars && index < 120) {
            val paragraph = paragraph(index)
            out += paragraph
            size += paragraph.length + 2
            index++
        }
        return out
    }

    fun probe(): List<String> = paragraphs(520).take(2)

    private fun paragraph(index: Int): String {
        val start = (index * 4) % sentences.size
        val builder = StringBuilder()
        repeat(4) { offset ->
            builder.append(sentences[(start + offset) % sentences.size])
        }
        if (index % 3 == 0) {
            builder.append(dialogues[index % dialogues.size])
        }
        return builder.toString()
    }
